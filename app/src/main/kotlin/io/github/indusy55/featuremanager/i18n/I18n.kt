package io.github.indusy55.featuremanager.i18n

import java.util.Locale

/**
 * Lightweight localization layer. English is the default; Simplified Chinese is used when the
 * device locale is Chinese. Strings not present in [translations] are returned unchanged.
 */
fun String.i18n(): String {
    if (Locale.getDefault().language.equals("zh", ignoreCase = true)) return this
    translations[this]?.let { return it }
    return dynamicTranslation(this) ?: this
}

private fun dynamicTranslation(text: String): String? {
    val rules = listOf(
        Regex("^已生效 v(.+)$") to "Loaded v$1",
        Regex("^已生效 \\(v(.+)$") to "Loaded (v$1",
        Regex("^配置版本 v(.+)$") to "Config v$1",
        Regex("^加载时间：(.+)$") to "Loaded at: $1",
        Regex("^应用版本：(.+)$") to "App version: $1",
        Regex("^已应用模板：(.+)$") to "Applied templates: $1",
        Regex("^开启 (\\d+)$") to "Enabled $1",
        Regex("^关闭 (\\d+)$") to "Disabled $1",
        Regex("^共 (\\d+) 个模板$") to "$1 templates",
        Regex("^共 (\\d+) 项特性$") to "$1 features",
        Regex("^共 (\\d+) 条$") to "$1 rules",
        Regex("^目标应用 \\((\\d+)\\)$") to "Target apps ($1)",
        Regex("^已选择 (\\d+) 个应用(.*)$") to "Selected $1 apps$2",
        Regex("^作用域应用：(\\d+) 个$") to "Scoped apps: $1",
        Regex("^API 版本：(\\d+)$") to "API version: $1",
        Regex("^配置版本 \\(revision\\)：(\\d+)$") to "Config revision: $1",
        Regex("^已配置应用：(\\d+) · 自定义模板：(\\d+) · 已上报进程：(\\d+)$") to
            "Configured apps: $1 · custom templates: $2 · reported processes: $3",
        Regex("^没有名称或包名匹配“(.+)”的应用。$") to "No apps match \"$1\".",
        Regex("^没有名称或包名匹配“(.+)”的已配置应用。$") to "No config matches \"$1\".",
        Regex("^已将 (\\S+) 加入模块作用域$") to "Added $1 to module scope",
        Regex("^已将「(.+)」应用到 (\\d+) 个应用$") to "Applied \"$1\" to $2 apps",
        Regex("^已复制为自定义模板：(.+)$") to "Copied as custom template: $1",
        Regex("^已合并应用模板：(.+)$") to "Merged template: $1",
        Regex("^已替换规则并应用模板：(.+)$") to "Replaced rules with template: $1",
        Regex("^已清空 (.+) 的规则$") to "Cleared rules for $1",
        Regex("^已添加并强制开启：(.+)$") to "Added and force-enabled: $1",
        Regex("^模板「(.+)」已保存$") to "Template \"$1\" saved",
        Regex("^模板「(.+)」已删除$") to "Template \"$1\" deleted",
        Regex("^确定删除自定义模板「(.+)」？此操作不可撤销。$") to "Delete custom template \"$1\"? This cannot be undone.",
        Regex("^确定删除模板「(.+)」？此操作不可撤销。$") to "Delete template \"$1\"? This cannot be undone.",
        Regex("^配置导入成功，恢复 (\\d+) 项应用配置$") to "Config imported; restored $1 app configs",
        Regex("^导入失败：(.+)$") to "Import failed: $1",
        Regex("^配置已复制到剪贴板（(\\d+) 字符）$") to "Config copied to clipboard ($1 chars)",
        Regex("^最近消息：(.+)$") to "Latest message: $1",
        Regex("^已将 (\\d+) 个应用加入模块作用域$") to "Added $1 apps to module scope",
        Regex("^已从模块作用域移除 (\\d+) 个应用$") to "Removed $1 apps from module scope",
        Regex("^…另有 (\\d+) 个进程$") to "…and $1 more processes"
    )
    for ((regex, replacement) in rules) {
        if (regex.matches(text)) return regex.replace(text, replacement)
    }
    return null
}

